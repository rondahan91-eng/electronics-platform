function evaluate23(level, val) {
  const q = level.question;
  if (q.kind === 'row-count' || q.kind === 'read-table') {
    if (val === q.answer) return { outcome: 'correct', value: val };
    if (q.traps && Object.prototype.hasOwnProperty.call(q.traps, val)) {
      return { outcome: 'incorrect', value: val, message: q.traps[val] };
    }
    return {
      outcome: 'incorrect', value: val,
      message: q.kind === 'row-count'
        ? 'לא מדויק - מספר השורות בטבלת אמת שווה ל-2 בחזקת מספר הפסוקים הבסיסיים.'
        : 'לא מדויק - עברו שורה-שורה על עמודת התוצאה (הימנית) וספרו כמה פעמים מופיע שם "אמת".',
    };
  }
  // complete-cell
  return evaluateCategorical(q, val);
}

