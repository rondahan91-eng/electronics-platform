/** מנרמל תשובת טקסט עברית: מסיר רווחים/מקפים וגרשיים/גרשות, בלי toUpperCase
 * (לא רלוונטי לעברית) ובלי מפת-נרדפות - מונח קנוני מדויק אחד בלבד לכל מושג. */
function normalizeLogicWord(raw) {
  return String(raw).trim()
    .replace(/[׳״'"]/g, '')
    .replace(/[\s\-–]+/g, '')
    .replace(/[.!?׃]+$/, '');
}

/** שלושת הצירים הקטגוריאליים היחידים בכל הטופיק - כל אחד עם 2 ערכים קנוניים
 * בדיוק, ותיאור-שאלה קצר המשמש להודעת ה-guard חוצה-הצירים. */
const AXES = {
  isprop: { values: ['פסוק', 'לא פסוק'], qDesc: 'האם המשפט הוא בכלל פסוק (יש לו ערך אמת) או לא' },
  atomic: { values: ['בסיסי', 'מורכב'], qDesc: 'האם הפסוק בסיסי או מורכב (מבנה הפסוק)' },
  truth: { values: ['אמת', 'שקר'], qDesc: 'מהו ערך האמת של הפסוק - אמת או שקר' },
};

/** guard חוצה-צירים, משותף לכל 12 השלבים הקטגוריאליים (1-6,8-12,15): אם
 * הערך המנורמל שהוזן שייך לציר *אחר* מזה שנשאל - למשל עונים 'אמת'/'שקר'
 * בשלב is-prop, או 'פסוק'/'לא פסוק' בשלב truth-value - מוחזרת הודעת בלבול-
 * קטגוריה ייעודית (לא הודעה גנרית), במקום ליפול להודעת "לא מדויק" רגילה. */
function crossAxisGuard(norm, ownAxis) {
  for (const [key, axis] of Object.entries(AXES)) {
    if (key === ownAxis) continue;
    if (axis.values.some(v => normalizeLogicWord(v) === norm)) {
      return {
        outcome: 'incorrect', value: norm,
        message: `כאן השאלה היא ${AXES[ownAxis].qDesc} - לא ${axis.qDesc}. ענו במונחים המתאימים לשאלה שנשאלה בפועל: ${AXES[ownAxis].values.join(' / ')}.`,
      };
    }
  }
  return null;
}

/** בדיקה גנרית לשלב קטגוריאלי בציר נתון (2 ערכים קנוניים בלבד): נכון / guard
 * חוצה-ציר / מלכודת "הערך הקנוני האחר" (עם ההסבר הספציפי לשלב) / נפילה
 * גנרית. משמש את כל 12 השלבים הקטגוריאליים בכל שלושת תתי-הנושאים. */
function evaluateCategorical(q, val) {
  const norm = normalizeLogicWord(val);
  // ציר 'atomic' בלבד: הניסוח בשאלה עצמה מציע "פסוק בסיסי"/"פסוק מורכב" (לא
  // רק "בסיסי"/"מורכב"), אז תלמיד/ה שעונים במילים המדויקות של השאלה חייבים
  // להתקבל - מסירים קידומת "פסוק" רק כאן, לא בהשוואה חוצה-צירים (שם "פסוק"
  // כערך גולמי שייך לציר isprop ואסור לגעת בו).
  const ownMatch = q.axis === 'atomic' ? norm.replace(/^פסוק/, '') : norm;
  if (ownMatch === normalizeLogicWord(q.answer)) return { outcome: 'correct', value: norm };
  const guard = crossAxisGuard(norm, q.axis);
  if (guard) return guard;
  const other = AXES[q.axis].values.find(v => v !== q.answer);
  if (ownMatch === normalizeLogicWord(other)) {
    return { outcome: 'incorrect', value: norm, message: q.wrongMsg };
  }
  return { outcome: 'incorrect', value: norm, message: `התשובה חייבת להיות אחת מהמילים: ${AXES[q.axis].values.join(' / ')}.` };
}

