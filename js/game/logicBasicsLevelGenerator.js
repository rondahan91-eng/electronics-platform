// -------------------------------------------------------------- דיספצ'ר
function groupOf(localId) {
  if (localId <= 7) return '2.1';
  if (localId <= 12) return '2.2';
  return '2.3';
}

function generateForLocal(localId) {
  const group = groupOf(localId);
  if (group === '2.1') return generate21(localId, LEVEL_DEFS_21[localId - 1]);
  if (group === '2.2') return generate22(localId, LEVEL_DEFS_22[localId - 8]);
  return generate23(localId, LEVEL_DEFS_23[localId - 13]);
}

const TOTAL_LEVELS = 16;
const cache = new Map();

export function generateLogicBasicsLevel(localId) {
  if (cache.has(localId)) return cache.get(localId);
  const group = groupOf(localId);
  const g = generateForLocal(localId);
  const { title, desc, prompt, answer, inputMode, hints: _defHints, ...rest } = g;
  const hints = buildHints(group, g);

  const question = { prompt, unit: '', answer, hints, ...rest };
  if (inputMode === 'text') question.inputMode = 'text';

  const level = {
    id: localId, title, description: desc,
    world: { group, answer, ...rest },
    question,
  };
  cache.set(localId, level);
  return level;
}

export function topicLevelCount() { return TOTAL_LEVELS; }

// ---------------------------------------------------------------- הערכת תשובה
export function evaluateLogicBasicsAnswer(level, val) {
  switch (level.world.group) {
    case '2.1': return evaluate21(level, val);
    case '2.2': return evaluate22(level, val);
    default: return evaluate23(level, val);
  }
}
