export function chapterKey(sectionKey, chapterN) { return `${sectionKey}#${chapterN}`; }

/** כל הפרקים במאגר, שטוח, עם ה-section ומפתח ייחודי מוכנים. */
export function allChapters() {
  return SYLLABUS.reduce((acc, sec) =>
    acc.concat(sec.items.map(item => ({ sec, item, key: chapterKey(sec.key, item.n) }))), []);
}

export function chapterByKey(key) {
  return allChapters().find(c => c.key === key) || null;
}

/** האם לפרק יש בכלל תת-נושא בר-תרגול (מבחין "יש כבר משהו" מ"עוד לא"). */
export function chapterHasPractice(item) {
  return (item.subs || []).some(sb => !!sb.topicId);
}

/** מפתחות כל הפרקים שיש להם תרגול אמיתי כרגע - ברירת מחדל סבירה ל"חשוף". */
export const DEFAULT_REVEALED = allChapters()
  .filter(c => chapterHasPractice(c.item))
  .map(c => c.key);
