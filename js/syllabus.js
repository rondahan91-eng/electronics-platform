import { TOPICS } from './curriculum.js';

/** בונה מקטע "תרגול" שמצביע על טווח שלבים אמיתי בתוך topic קיים.
 * levelEnd ריק = "עד סוף הנושא" (נגזר דינמית מ-TOPICS, לא מספר קבוע -
 * כדי לא ליצור עוד דריפט כמו שכבר תפסנו כמה פעמים בפרויקט הזה). */
function practice(topicId, levelStart, levelEnd) {
  const topic = TOPICS[topicId];
  const end = levelEnd ?? (topic ? topic.totalLevels : levelStart);
  return { topicId, levelStart, levelEnd: end, total: end - levelStart + 1 };
}

