"""Hints, stage titles and check rules of the knights-and-knaves chapter, written for the method the teacher taught in class
(deck "צדיקים ונוכלים"): the speaker's consistency condition is an "if and only if" sentence  x ⟺ (what he said), a row is consistent
when the condition of every speaker is true. Stages 1-2 are written by hand per exercise; stages 3-4 are generated from the exercise
structure (so every worked example is computed, never typed). In the texts {..} marks an LTR formula (one bidi isolate).
Used by gen_data.py:  HINTS = build_hints(exercise_structure) ->  {'1': [3 strings], ..., '4': [3 strings]}."""
import re

LRI, PDI = '⁦', '⁩'
HEB = re.compile('[א-ת]+')
SYM = {'and': '∧', 'or': '∨'}


def F(x):
    return LRI + x + PDI


def T(s):
    """{x ⟺ (¬x ∧ L)} -> one isolate."""
    return re.sub(r'\{([^}]*)\}', lambda m: F(m.group(1)), s)


def EQ(s):
    """An equation as its own block: every Hebrew word (אמת / שקר) is isolated so that the equation reads left to right."""
    body = HEB.sub(lambda w: LRI + w.group(0) + PDI, s)
    return '<span class="kn-eq">' + LRI + body + PDI + '</span>'


def tf(b):
    return 'אמת' if b else 'שקר'


def lit_s(l):
    return ('¬' if l[1] else '') + l[0]


def sent_s(s):
    return '%s %s %s' % (lit_s(s['lits'][0]), SYM[s['op']], lit_s(s['lits'][1]))


def cond_s(s):
    return '%s ⟺ (%s)' % (s['speaker'], sent_s(s))


def rows_of(e):
    n = len(e['vars'])
    out = []
    for i in range(1 << n):
        out.append({v: not ((i >> (n - 1 - k)) & 1) for k, v in enumerate(e['vars'])})
    return out


def eval_lit(vals, l):
    return (not vals[l[0]]) if l[1] else vals[l[0]]


def eval_sent(vals, s):
    a, b = eval_lit(vals, s['lits'][0]), eval_lit(vals, s['lits'][1])
    return (a and b) if s['op'] == 'and' else (a or b)


def who(e, v):
    for p in e['people']:
        if p['v'] == v:
            return p['name']
    for f in e['facts']:
        if f['v'] == v:
            return f['label']
    return v


def vals_text(e, vals):
    items = ['{%s}=%s' % (v, tf(vals[v])) for v in e['vars']]
    return items[0] if len(items) == 1 else ', '.join(items[:-1]) + ' ו-' + items[-1]


def chain_sentence(s, vals):
    """¬x ∧ L = ¬אמת ∧ אמת = שקר ∧ אמת = שקר   (the sentence, substitution, negations, the connective)."""
    l0, l1 = s['lits']
    subst = '%s%s %s %s%s' % ('¬' if l0[1] else '', tf(vals[l0[0]]), SYM[s['op']], '¬' if l1[1] else '', tf(vals[l1[0]]))
    neg = '%s %s %s' % (tf(eval_lit(vals, l0)), SYM[s['op']], tf(eval_lit(vals, l1)))
    steps = [sent_s(s), subst] + ([neg] if neg != subst else []) + [tf(eval_sent(vals, s))]
    return ' = '.join(steps)


def chain_condition(s, vals):
    """x ⟺ (¬x ∧ L) = אמת ⟺ שקר = שקר   (the condition, the two sides' values, its value)."""
    said, val = vals[s['speaker']], eval_sent(vals, s)
    return '%s = %s ⟺ %s = %s' % (cond_s(s), tf(said), tf(val), tf(said == val))


