def build_hints(e):
    n = e['n']
    sents = e['sentences']
    many = len(sents) > 1
    nrows = 1 << len(e['vars'])
    ex_vals = rows_of(e)[0]          # row 1: everything true (never the solution row)
    vars_he = ('{%s}' % e['vars'][0]) if len(e['vars']) == 1 else ', '.join('{%s}' % v for v in e['vars'][:-1]) + ' ו-{%s}' % e['vars'][-1]
    h = {'1': [T(x) for x in HAND[n]['1']], '2': [T(x) for x in HAND[n]['2']]}

    # ---- stage 3: the sentence values per row
    def rule_of(s):
        return 'בקשר "וגם" הפסוק אמת רק כששני החלקים אמת' if s['op'] == 'and' else 'בקשר "או" הפסוק אמת כבר כשאחד משני החלקים אמת'
    if many:
        names = [who(e, s['speaker']) for s in sents]
        rules = ' ; '.join('בפסוק של %s %s' % (names[i], rule_of(s)) for i, s in enumerate(sents))
        rules = rules.replace(' ; ', '. ')
        s3a = 'יש %d שילובים אפשריים של אמת/שקר עבור %s, ולכן %d שורות. בכל שורה יש שני פסוקים לחשב, אחד לכל דובר. %s. בשלב הזה ממלאים רק את עמודות "הפסוק".' % (nrows, vars_he, nrows, rules)
        s3b = 'בכל שורה מציבים את ערכי המשתנים בתוך כל פסוק, מחשבים קודם את השלילות ואחר כך את הקשר, ורושמים את התוצאה בעמודת "הפסוק" של אותו דובר. שני הפסוקים מחושבים בנפרד, מאותם ערכי משתנים שבאותה שורה.'
        if n == 5:
            s3b += ' שימו לב שהפסוק של ל׳ לא תלוי בערך ש-{l} עצמו קיבל באותה שורה.'
    else:
        s3a = 'יש %d שילובים אפשריים של אמת/שקר עבור %s, ולכן %d שורות. %s. בשלב הזה ממלאים רק את עמודת "הפסוק".' % (nrows, vars_he, nrows, rule_of(sents[0]))
        s3b = 'בכל שורה מציבים את ערכי המשתנים בתוך הפסוק {%s}, מחשבים קודם את השלילות ואחר כך את הקשר, ורושמים את התוצאה (אמת/שקר) בעמודת "הפסוק".' % sent_s(sents[0])
    chains3 = ''.join(EQ(chain_sentence(s, ex_vals)) for s in sents)
    s3c = 'לדוגמה בשורה 1 (%s): מציבים, מחשבים את השלילות, ואז את הקשר.%s חשבו באותו אופן את שאר השורות.' % (vals_text(e, ex_vals), chains3)
    h['3'] = [T(s3a), T(s3b), T(s3c)]

